//! Building plugin.wasm reproducibly and assembling the package folder with its file list.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::fs;
use std::path::{Path, PathBuf};

use plugin_format::package::LIST_NAME;
use plugin_format::{Manifest, PackageList};
use serde_json::Value;

use crate::process;

/// The plugin crate lives here; its package name is read from its Cargo.toml,
/// so renaming the plugin needs no change to this tool.
const PLUGIN_MANIFEST: &str = "plugin/Cargo.toml";
pub const TARGET: &str = "wasm32-wasip2";

/// Licence and notice files copied into THIRD-PARTY-LICENSES, by name prefix.
const LICENCE_FILE_PREFIXES: &[&str] = &["LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"];

/// Build the component. Paths are rewritten so the bytes do not depend on
/// where the source or the cargo cache sits on the building machine.
pub fn build_module(root: &Path) -> Result<PathBuf, String> {
    let flags = [
        format!("--remap-path-prefix={}=/plugin", root.display()),
        format!("--remap-path-prefix={}=/cargo", cargo_home()?.display()),
    ]
    .join("\u{1f}");
    let plugin = PluginCrate::locate(root)?;
    let args = [
        "build",
        "-p",
        plugin.name.as_str(),
        "--target",
        TARGET,
        "--release",
        "--locked",
    ];
    process::cargo(root, &args, &[("CARGO_ENCODED_RUSTFLAGS", flags.as_str())])?;
    let artifact = format!("{}.wasm", plugin.name.replace('-', "_"));
    let module = plugin
        .target_dir
        .join(TARGET)
        .join("release")
        .join(artifact);
    if !module.is_file() {
        return Err(format!("the build did not produce {}", module.display()));
    }
    Ok(module)
}

/// Assemble dist/<id>-<version>/ and write its canonical `package` list.
pub fn package(root: &Path, manifest: &Manifest, module: &Path) -> Result<PathBuf, String> {
    let name = format!("{}-{}", manifest.plugin.id, manifest.plugin.version);
    let dir = root.join("dist").join(name);
    reset_dir(&dir)?;
    copy(
        &root.join("syrinx-plugin.toml"),
        &dir.join("syrinx-plugin.toml"),
    )?;
    copy(module, &dir.join(&manifest.entry.module))?;
    copy(&root.join("LICENSE"), &dir.join("LICENSE"))?;
    if let Some(ui) = &manifest.entry.ui {
        copy_tree(&root.join(ui), &dir.join(ui))?;
    }
    let notices = third_party_licences(root)?;
    write(&dir.join("THIRD-PARTY-LICENSES"), &notices)?;
    let list = PackageList::from_folder(
        &dir,
        &manifest.plugin.id,
        &manifest.plugin.version,
        &manifest.interface.world,
    )
    .map_err(|error| error.to_string())?;
    write(&dir.join(LIST_NAME), &list.render())?;
    Ok(dir)
}

/// Every crate compiled into plugin.wasm, with its licence files, in a fixed order.
fn third_party_licences(root: &Path) -> Result<String, String> {
    let args = [
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--filter-platform",
        TARGET,
    ];
    let metadata: Value = serde_json::from_str(&process::cargo_output(root, &args)?)
        .map_err(|error| format!("cargo metadata printed invalid JSON: {error}"))?;
    let plugin = PluginCrate::locate(root)?;
    let bundled = bundled_packages(&metadata, &plugin.name)?;
    let mut text = String::from(
        "Third-party software compiled into plugin.wasm\n\
         Generated by `cargo xtask build` from Cargo.lock; do not edit.\n",
    );
    for package in bundled {
        text.push_str(&describe(&package)?);
    }
    Ok(text)
}

/// Walk normal (not build or dev) dependencies from the plugin crate, stopping
/// at procedural macros, which run on the build machine and are not bundled.
fn bundled_packages(metadata: &Value, plugin_name: &str) -> Result<Vec<Value>, String> {
    let packages: BTreeMap<&str, &Value> = metadata["packages"]
        .as_array()
        .ok_or("cargo metadata has no packages")?
        .iter()
        .filter_map(|package| Some((package["id"].as_str()?, package)))
        .collect();
    let nodes: BTreeMap<&str, &Value> = metadata["resolve"]["nodes"]
        .as_array()
        .ok_or("cargo metadata has no resolve graph")?
        .iter()
        .filter_map(|node| Some((node["id"].as_str()?, node)))
        .collect();
    let start = packages
        .iter()
        .find(|(_, package)| package["name"] == plugin_name)
        .map(|(id, _)| *id)
        .ok_or("the plugin crate is not in cargo metadata")?;

    let mut seen = BTreeSet::from([start]);
    let mut queue = VecDeque::from([start]);
    while let Some(id) = queue.pop_front() {
        for dependency in normal_dependencies(nodes.get(id)) {
            let is_macro = packages.get(dependency).is_some_and(|p| is_proc_macro(p));
            if !is_macro && seen.insert(dependency) {
                queue.push_back(dependency);
            }
        }
    }
    seen.remove(start);
    let mut bundled: Vec<Value> = seen
        .iter()
        .filter_map(|id| packages.get(id).map(|package| (*package).clone()))
        .collect();
    bundled.sort_by_key(|package| (package["name"].to_string(), package["version"].to_string()));
    Ok(bundled)
}

fn normal_dependencies<'a>(node: Option<&&'a Value>) -> Vec<&'a str> {
    let Some(deps) = node.and_then(|node| node["deps"].as_array()) else {
        return Vec::new();
    };
    deps.iter()
        .filter(|dep| {
            dep["dep_kinds"]
                .as_array()
                .is_some_and(|kinds| kinds.iter().any(|kind| kind["kind"].is_null()))
        })
        .filter_map(|dep| dep["pkg"].as_str())
        .collect()
}

fn is_proc_macro(package: &Value) -> bool {
    package["targets"].as_array().is_some_and(|targets| {
        targets.iter().any(|target| {
            target["kind"]
                .as_array()
                .is_some_and(|kinds| kinds.iter().any(|kind| kind == "proc-macro"))
        })
    })
}

/// One crate's heading, then the text of each licence file it ships.
fn describe(package: &Value) -> Result<String, String> {
    let name = package["name"].as_str().unwrap_or("?");
    let version = package["version"].as_str().unwrap_or("?");
    let licence = package["license"].as_str().unwrap_or("(no licence field)");
    let repository = package["repository"].as_str().unwrap_or("(no repository)");
    let mut text = format!(
        "\n{rule}\n{name} {version}\nLicence: {licence}\nSource: {repository}\n{rule}\n",
        rule = "=".repeat(72)
    );
    let manifest_path = package["manifest_path"]
        .as_str()
        .ok_or_else(|| format!("{name} has no manifest path"))?;
    let crate_dir = Path::new(manifest_path)
        .parent()
        .ok_or_else(|| format!("{name} has no crate folder"))?;
    let files = licence_files(crate_dir)?;
    if files.is_empty() {
        return Err(format!(
            "{name} {version} ships no licence file, so THIRD-PARTY-LICENSES would lack its text"
        ));
    }
    for file in files {
        let body = fs::read_to_string(&file)
            .map_err(|error| format!("cannot read {}: {error}", file.display()))?;
        let file_name = file
            .file_name()
            .map(|n| n.to_string_lossy())
            .unwrap_or_default();
        text.push_str(&format!(
            "\n--- {file_name} ---\n{}\n",
            body.replace("\r\n", "\n").trim_end()
        ));
    }
    Ok(text)
}

fn licence_files(crate_dir: &Path) -> Result<Vec<PathBuf>, String> {
    let entries = fs::read_dir(crate_dir)
        .map_err(|error| format!("cannot list {}: {error}", crate_dir.display()))?;
    let mut files = Vec::new();
    for entry in entries {
        let path = entry.map_err(|error| error.to_string())?.path();
        let name = path
            .file_name()
            .map(|n| n.to_string_lossy().to_ascii_uppercase())
            .unwrap_or_default();
        if path.is_file()
            && LICENCE_FILE_PREFIXES
                .iter()
                .any(|prefix| name.starts_with(prefix))
        {
            files.push(path);
        }
    }
    files.sort();
    Ok(files)
}

/// The plugin crate's package name, and where cargo writes build output.
pub struct PluginCrate {
    pub name: String,
    target_dir: PathBuf,
}

impl PluginCrate {
    /// Ask cargo for the package at plugin/Cargo.toml (honours CARGO_TARGET_DIR).
    pub fn locate(root: &Path) -> Result<Self, String> {
        let args = ["metadata", "--format-version", "1", "--no-deps", "--locked"];
        let metadata: Value = serde_json::from_str(&process::cargo_output(root, &args)?)
            .map_err(|error| format!("cargo metadata printed invalid JSON: {error}"))?;
        let manifest = root.join(PLUGIN_MANIFEST);
        let name = metadata["packages"]
            .as_array()
            .into_iter()
            .flatten()
            .find(|package| package["manifest_path"].as_str().map(Path::new) == Some(&manifest))
            .and_then(|package| package["name"].as_str())
            .ok_or_else(|| format!("no workspace package at {}", manifest.display()))?;
        let target_dir = metadata["target_directory"]
            .as_str()
            .ok_or("cargo metadata has no target directory")?;
        Ok(Self {
            name: name.to_owned(),
            target_dir: PathBuf::from(target_dir),
        })
    }
}

fn cargo_home() -> Result<PathBuf, String> {
    if let Some(home) = std::env::var_os("CARGO_HOME") {
        return Ok(PathBuf::from(home));
    }
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .ok_or("neither CARGO_HOME nor a home folder is set")?;
    Ok(PathBuf::from(home).join(".cargo"))
}

/// Start from an empty folder; dist/ holds only build output.
fn reset_dir(dir: &Path) -> Result<(), String> {
    if dir.exists() {
        fs::remove_dir_all(dir)
            .map_err(|error| format!("cannot clear {}: {error}", dir.display()))?;
    }
    fs::create_dir_all(dir).map_err(|error| format!("cannot create {}: {error}", dir.display()))
}

fn copy(from: &Path, to: &Path) -> Result<(), String> {
    if let Some(parent) = to.parent() {
        fs::create_dir_all(parent).map_err(|error| error.to_string())?;
    }
    fs::copy(from, to)
        .map(|_| ())
        .map_err(|error| format!("cannot copy {}: {error}", from.display()))
}

/// Copy a folder's regular files, refusing links so nothing outside is packaged.
fn copy_tree(from: &Path, to: &Path) -> Result<(), String> {
    let entries =
        fs::read_dir(from).map_err(|error| format!("cannot list {}: {error}", from.display()))?;
    for entry in entries {
        let entry = entry.map_err(|error| error.to_string())?;
        let kind = entry.file_type().map_err(|error| error.to_string())?;
        let target = to.join(entry.file_name());
        if kind.is_dir() {
            copy_tree(&entry.path(), &target)?;
        } else if kind.is_file() {
            copy(&entry.path(), &target)?;
        } else {
            return Err(format!(
                "{} is a link; packages hold plain files only",
                entry.path().display()
            ));
        }
    }
    Ok(())
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    fs::write(path, text).map_err(|error| format!("cannot write {}: {error}", path.display()))
}
